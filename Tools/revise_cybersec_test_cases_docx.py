def _set_cell_text(cell, text: str) -> None:
    cell.text = text


def _clear_table_data_rows(table) -> None:
    while len(table.rows) > 1:
        table._tbl.remove(table.rows[-1]._tr)


def _add_row(table, values: list[str]) -> None:
    row = table.add_row()
    for i, val in enumerate(values):
        _set_cell_text(row.cells[i], val)


def main() -> None:
    if not SRC.exists():
        raise FileNotFoundError(SRC)

    doc = Document(str(SRC))
    table = doc.tables[0]

    # 更新表头
    for j, h in enumerate(HEADERS):
        _set_cell_text(table.rows[0].cells[j], h)

    _clear_table_data_rows(table)
    for row in ROWS:
        _add_row(table, row)

    doc.save(str(OUT))
    print(f"已写入: {OUT}")
    print(f"共 {len(ROWS)} 条用例（原稿 35 条）")


if __name__ == "__main__":
    main()
